let cache: ResolvedPath | null = null

export function getAgentsPath(): ResolvedPath {
  if (cache) return cache
  const all = (getCurriculumIndex().lessonsByTrack.agents || []).filter((l) => Number(l.title.slice(0, 2)) < 10)
  cache = resolvePath(all, STAGES)
  return cache
}
